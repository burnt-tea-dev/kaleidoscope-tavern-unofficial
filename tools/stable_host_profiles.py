"""Exact approved stable-author host declarations, without private implementation.

Existing profiles are unchanged. New author identities and public API versions
are admitted only with reviewed declaration digests, original/output hashes,
helper hashes and their explicitly compatible preceding source receipts.
"""
import copy
import hashlib
import json
import re
import subprocess
from pathlib import Path

CATALOG = json.loads(Path(__file__).with_suffix('.json').read_text())
_PUBLIC_CATALOG = copy.deepcopy(CATALOG)
PROFILES = CATALOG['profiles']
CURATED = 'current-author-curated'
CURATED_KEY = 'current_author_curated'
CURATED_INPUT = 'companion-sources/current-author-curated/profile.json'


def curated_profile(catalog_data=None):
    """One reviewed selection binds the producer and admission; absence is not approval."""
    profiles = PROFILES if catalog_data is None else catalog_data['profiles']
    catalog_data = CATALOG if catalog_data is None else catalog_data
    catalog = catalog_data.get(CURATED_KEY)
    if not isinstance(catalog, dict):
        raise ValueError('Curated author profile has no reviewed catalog binding')
    selection = catalog['selection']
    if selection['path'] != CURATED_INPUT or not re.fullmatch('[0-9a-f]{64}', selection['sha256']):
        raise ValueError('Curated author profile input binding differs')
    value = selection['value']
    if value['schema'] != 1 or value['kind'] != CURATED or any(value[key] != catalog[key] for key in ('profile', 'version')):
        raise ValueError('Curated author profile identity differs')
    if not value['sources'] or len(set(value['sources'])) != len(value['sources']):
        raise ValueError('Curated functional sources must be explicit and unique')
    supported = {'cookery-station-performance': 'Cookery', 'fishing-current': 'Fishing', 'witchway-native-drop-items': 'WitchWay'}
    checks = value['functional_checks']
    if not checks or set(checks) - supported.keys() or {row['source'] for row in checks.values()} != set(value['sources']):
        raise ValueError('Curated functional checks do not cover the selected sources')
    if any(row['source'] != supported[name] or type(row['cases']) is not int or row['cases'] <= 0 for name, row in checks.items()):
        raise ValueError('Curated functional check contract differs')
    if not value['domains'] or not value['checks'] or len(set(value['checks'])) != len(value['checks']) or not {'current-source-api', 'current-runtime-functional.json'} <= set(value['checks']):
        raise ValueError('Curated runtime requires explicit domains and source checks')
    if set(value['check_commands']) != set(value['checks']):
        raise ValueError('Curated source checks lack exact commands')
    if any(not isinstance(command, list) or not command or not all(isinstance(arg, str) and arg for arg in command) for command in value['check_commands'].values()):
        raise ValueError('Curated check command missing')
    contract = value['functional_contract']
    for name in [contract['path'], *[path for paths in value['domains'].values() for path in paths]]:
        path = Path(name)
        if not name or path.is_absolute() or '..' in path.parts or '\\' in name or path.as_posix() != name:
            raise ValueError('Unsafe curated source path')
    if not re.fullmatch('[0-9a-f]{64}', contract['sha256']):
        raise ValueError('Curated runtime contract digest missing')
    if value['authors'] != catalog['authors'] or set(value['pack_versions']) != set(catalog['authors']):
        raise ValueError('Curated author output identities differ')
    for pair in value['pack_versions'].values():
        if set(pair) != {'BP', 'RP'} or any(not isinstance(v, list) or len(v) != 3 or any(type(n) is not int or n < 0 for n in v) for v in pair.values()):
            raise ValueError('Curated author paired output version missing')
    # The exact station declaration is generated by the private owner later.
    # A new author UUID alone must never select the legacy wiring contract.
    station = profiles[value['station_profile']]
    if station.get('admission') != CURATED or station.get('id') != 'senluo:cookery-station-performance':
        raise ValueError('Curated station owner is not reviewed')
    return catalog


def bind_source_catalog(source_root):
    """Load committed owner metadata locally; never publish it in this catalog.

    The caller retains canonical repository identity and CI verification. This
    boundary binds the optional catalog to that source's committed baseline;
    a catalog cannot replace public declarations or weaken receipt checks.
    """
    root = Path(source_root).resolve() if source_root is not None else None
    baseline = root / 'baseline.json' if root is not None else None
    config = json.loads(baseline.read_bytes()) if baseline is not None and baseline.is_file() else {}
    reference = config.get('host_catalog')
    merged = copy.deepcopy(_PUBLIC_CATALOG)
    if reference is not None:
        if not isinstance(reference, dict) or set(reference) != {'path', 'sha256'}:
            raise ValueError('Owner host catalog needs an exact path and digest')
        name, expected = reference['path'], reference['sha256']
        if not isinstance(name, str) or not name or not isinstance(expected, str) or not re.fullmatch('[0-9a-f]{64}', expected):
            raise ValueError('Owner host catalog binding is invalid')
        relative = Path(name)
        if relative.is_absolute() or '..' in relative.parts or '\\' in name or relative.as_posix() != name:
            raise ValueError('Owner host catalog path is unsafe')
        path = root / relative
        if path.is_symlink() or not path.is_file() or not path.resolve().is_relative_to(root):
            raise ValueError('Owner host catalog is missing or outside its source')
        def committed(name):
            return subprocess.check_output(['git', 'show', 'HEAD:' + name], cwd=root, stderr=subprocess.PIPE)
        raw = path.read_bytes()
        if baseline.read_bytes() != committed('baseline.json') or raw != committed(name):
            raise ValueError('Owner host catalog and baseline must be committed together')
        if hashlib.sha256(raw).hexdigest() != expected:
            raise ValueError('Owner host catalog digest differs')
        owner = json.loads(raw)
        if not isinstance(owner, dict) or set(owner) != {'schema', 'profiles', CURATED_KEY} or owner['schema'] != 1:
            raise ValueError('Owner host catalog schema differs')
        profiles = owner['profiles']
        if not isinstance(profiles, dict) or not profiles or set(profiles) & merged['profiles'].keys():
            raise ValueError('Owner host catalog cannot replace public profiles')
        merged['profiles'].update(profiles)
        merged[CURATED_KEY] = owner[CURATED_KEY]
        curated_profile(merged)
    # Preserve the dictionary identities imported by the existing validators.
    PROFILES.clear()
    PROFILES.update(merged['profiles'])
    CATALOG.clear()
    CATALOG.update({**merged, 'profiles': PROFILES})
    return reference


def declaration_sha(spec):
    return hashlib.sha256(json.dumps(spec, sort_keys=True, separators=(',', ':'), ensure_ascii=False).encode()).hexdigest()


def receipt(profile):
    result = {key: profile[key] for key in ['id', 'version', 'original_files', 'patched_files', 'copies']}
    if profile.get('removed_files'):
        result['removed_files'] = profile['removed_files']
    return result


def public_profiles():
    return {'public-api': CATALOG['public_api_profile'], **CATALOG.get('public_api_profiles', {})}


def public_predecessors(profile):
    # The original receipt remains the default. Only the named, unchanged
    # private declarations may use another reviewed public API predecessor.
    for name, accepted in CATALOG.get('public_api_predecessors', {}).items():
        if PROFILES.get(name) == profile:
            profiles = public_profiles()
            return [receipt(profiles[key]) for key in accepted]
    # Any reviewed public API receipt is an acceptable predecessor for a
    # current host declaration. The source still has to carry one exact
    # receipt; only the redundant per-profile lookup key is removed.
    reviewed = [receipt(value) for value in public_profiles().values()
                if isinstance(value, dict) and all(key in value for key in
                ('id', 'version', 'original_files', 'patched_files', 'copies'))]
    return [CATALOG['public_api'], *reviewed]


def validate_stable_source(profile, source):
    if source.get('owner') != profile['source_owner'] or source.get('archive_sha256') != profile['archive_sha256']:
        raise ValueError('stable host requires its exact preceding author source')
    prior = source.get('reviewed_extensions', [])
    if not isinstance(prior, list):
        raise ValueError('stable host preceding receipts must be a list')
    for name in profile['required_extensions']:
        expected = public_predecessors(profile) if name == 'public-api' else [receipt(PROFILES[name])]
        preceding = prior
        if name == 'public-api':
            public_ids = {p['id'] for p in public_profiles().values()} | {p['id'] for p in expected}
            preceding = [row for row in prior if isinstance(row, dict) and row.get('id') in public_ids]
            # A host has one public API source, not two sequential installations
            # or a mixture of a new identity and old helper hashes.
            if len(preceding) != 1:
                raise ValueError('stable host lacks exact preceding receipt: ' + name)
        def matches(row, option):
            if not isinstance(row, dict):
                return False
            if all(row.get(key) == value for key, value in option.items()):
                return True
            if name == 'public-api' and row.get('delegated_files'):
                from cookery_station_extension import validate_public_delegation
                try:
                    validate_public_delegation(row, option)
                    return True
                except (ValueError, KeyError, TypeError):
                    return False
            return False
        if not any(matches(row, option) for row in preceding for option in expected):
            raise ValueError('stable host lacks exact preceding receipt: ' + name)


def match_stable_profile(spec, owned_root=None, source=None):
    candidates = {**PROFILES, **public_profiles()}
    new_hosts = {p['host_uuid'] for p in candidates.values()}
    new_archives = {p.get('archive_sha256') for p in candidates.values()} - {None}
    if spec.get('host_uuid') not in new_hosts and spec.get('archive_sha256') not in new_archives:
        return None
    found = [(name, p) for name, p in candidates.items()
             if p['id'] == spec.get('id') and p['host_uuid'] == spec.get('host_uuid')]
    if not found:
        raise ValueError('unregistered stable host declaration')
    # Distinct owner releases may share the author UUID and extension ID.
    # Match the full reviewed declaration; never choose the newest by name.
    exact = [(name, profile) for name, profile in found if declaration_sha(spec) == profile['spec_sha256']]
    if len(exact) > 1 and owned_root is not None:
        root = Path(owned_root).resolve()

        def has_exact_helpers(profile):
            for record in profile['copies'].values():
                path = Path(owned_root) / record['source']
                if (path.is_symlink() or not path.resolve().is_relative_to(root) or not path.is_file() or
                        hashlib.sha256(path.read_bytes()).hexdigest() != record['sha256']):
                    return False
            return True

        exact = [(name, profile) for name, profile in exact if has_exact_helpers(profile)]
        if not exact:
            raise ValueError('stable host helper differs from the exact reviewed source')
    if len(exact) != 1:
        raise ValueError('stable host declaration differs from the exact reviewed profile: ' + spec['id'])
    name, profile = exact[0]
    if source is not None:
        validate_stable_source(profile, source)
    if owned_root is not None:
        for record in profile['copies'].values():
            path = owned_root / record['source']
            if path.is_symlink() or not path.resolve().is_relative_to(owned_root.resolve()) or not path.is_file():
                raise ValueError('stable host helper missing or outside owned source')
            if hashlib.sha256(path.read_bytes()).hexdigest() != record['sha256']:
                raise ValueError('stable host helper differs from the exact reviewed source')
    return profile


def current_author_profile(spec, owned_root=None, source=None):
    """A fresh owner uses one exact declaration, never an owner-version range."""
    profile = match_stable_profile(spec, owned_root, source)
    return profile if profile and profile.get('admission') in ('current-author-p55', 'current-author-p56', 'current-author-p57','current-author-p58', CURATED) else None
