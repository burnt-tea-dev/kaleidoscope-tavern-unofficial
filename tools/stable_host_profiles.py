"""Exact approved stable-author host declarations, without private implementation.

Existing profiles are unchanged. New author identities and public API versions
are admitted only with reviewed declaration digests, original/output hashes,
helper hashes and their explicitly compatible preceding source receipts.
"""
import copy
import hashlib
import json
import re
import subprocess
from pathlib import Path

CATALOG = json.loads(Path(__file__).with_suffix('.json').read_text())
PROFILES = CATALOG['profiles']
CURATED = 'current-author-curated'
CURATED_KEY = 'current_author_curated'
CURATED_INPUT = 'companion-sources/current-author-curated/profile.json'


def curated_profile():
    """One reviewed selection binds the producer and admission; absence is not approval."""
    catalog = CATALOG.get(CURATED_KEY)
    if not isinstance(catalog, dict):
        raise ValueError('Curated author profile has no reviewed catalog binding')
    selection = catalog['selection']
    if selection['path'] != CURATED_INPUT or not re.fullmatch('[0-9a-f]{64}', selection['sha256']):
        raise ValueError('Curated author profile input binding differs')
    value = selection['value']
    if value['schema'] != 1 or value['kind'] != CURATED or any(value[key] != catalog[key] for key in ('profile', 'version')):
        raise ValueError('Curated author profile identity differs')
    if not value['sources'] or len(set(value['sources'])) != len(value['sources']):
        raise ValueError('Curated functional sources must be explicit and unique')
    supported = {'cookery-station-performance': 'Cookery', 'fishing-current': 'Fishing', 'witchway-native-drop-items': 'WitchWay'}
    checks = value['functional_checks']
    if not checks or set(checks) - supported.keys() or {row['source'] for row in checks.values()} != set(value['sources']):
        raise ValueError('Curated functional checks do not cover the selected sources')
    if any(row['source'] != supported[name] or type(row['cases']) is not int or row['cases'] <= 0 for name, row in checks.items()):
        raise ValueError('Curated functional check contract differs')
    if not value['domains'] or not value['checks'] or len(set(value['checks'])) != len(value['checks']) or not {'current-source-api', 'current-runtime-functional.json'} <= set(value['checks']):
        raise ValueError('Curated runtime requires explicit domains and source checks')
    if set(value['check_commands']) != set(value['checks']):
        raise ValueError('Curated source checks lack exact commands')
    if any(not isinstance(command, list) or not command or not all(isinstance(arg, str) and arg for arg in command) for command in value['check_commands'].values()):
        raise ValueError('Curated check command missing')
    contract = value['functional_contract']
    for name in [contract['path'], *[path for paths in value['domains'].values() for path in paths]]:
        path = Path(name)
        if not name or path.is_absolute() or '..' in path.parts or '\\' in name or path.as_posix() != name:
            raise ValueError('Unsafe curated source path')
    if not re.fullmatch('[0-9a-f]{64}', contract['sha256']):
        raise ValueError('Curated runtime contract digest missing')
    if value['authors'] != catalog['authors'] or set(value['pack_versions']) != set(catalog['authors']):
        raise ValueError('Curated author output identities differ')
    for pair in value['pack_versions'].values():
        if set(pair) != {'BP', 'RP'} or any(not isinstance(v, list) or len(v) != 3 or any(type(n) is not int or n < 0 for n in v) for v in pair.values()):
            raise ValueError('Curated author paired output version missing')
    # The exact station declaration is generated by the private owner later.
    # A new author UUID alone must never select the legacy wiring contract.
    station = PROFILES[value['station_profile']]
    if station.get('admission') != CURATED or station.get('id') != 'senluo:cookery-station-performance':
        raise ValueError('Curated station owner is not reviewed')
    return catalog


def declaration_sha(spec):
    return hashlib.sha256(json.dumps(spec, sort_keys=True, separators=(',', ':'), ensure_ascii=False).encode()).hexdigest()


def curated_upstream_selection(lock, baseline, source_root):
    """Select only the committed private profile's reviewed author pairs.

    The full public lock remains a catalog. Its complement must be declared
    exactly by the public policy; callers cannot supply an exclusion list.
    The caller first validates the current private runtime conservation proof.
    """
    from family_update.current_author_validation import committed, current_selection
    from family_update.repository_identity import target

    def require(condition, message):
        if not condition:
            raise ValueError('Curated upstream selection: ' + message)

    root = Path(source_root)
    catalog = curated_profile()
    selection = current_selection(source_root=root)
    require(committed('baseline.json', source_root=root) == baseline, 'private baseline is not the committed input')
    require(baseline.get('repository') == 'local/senluo-amw-cuisine'
            and baseline.get('version') == selection['version'] == catalog['version'], 'private owner identity differs')
    identity = committed('.repo-target.json', source_root=root)
    expected = target('burnt-tea-dev/senluo-family-integration-private')
    require(all(identity.get(key) == value for key, value in expected.items())
            and identity.get('logical_runtime_repository') == baseline['repository'], 'private repository target differs')
    commit = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=root, text=True).strip()
    require(re.fullmatch('[0-9a-f]{40}', commit) is not None, 'private commit is missing')
    policy = catalog.get('upstream_selection')
    require(isinstance(policy, dict) and set(policy) == {'schema', 'kind', 'deferred'}
            and policy['schema'] == 1 and policy['kind'] == 'exact-curated-author-set', 'reviewed selection policy is missing')
    deferred = policy['deferred']
    authors = selection['authors']
    require(isinstance(deferred, dict) and isinstance(authors, dict) and bool(authors), 'author selection is empty')
    require(not set(authors) & set(deferred), 'active and deferred authors overlap')
    upstream = lock['upstream']
    require(isinstance(upstream, list), 'full upstream catalog is invalid')
    names, projects, files, archives, uuids = set(), set(), set(), set(), set()
    for row in upstream:
        require(isinstance(row, dict) and isinstance(row.get('name'), str) and bool(row['name']), 'author name is missing')
        require(row['name'] not in names, 'duplicate author name')
        names.add(row['name'])
        for field, seen in [('project_id', projects), ('file_id', files)]:
            value = row.get(field)
            require(type(value) is int and value > 0 and value not in seen, 'duplicate or invalid ' + field)
            seen.add(value)
        require(isinstance(row.get('sha256'), str) and re.fullmatch('[0-9a-f]{64}', row['sha256']) is not None
                and row['sha256'] not in archives, 'duplicate or invalid archive digest')
        archives.add(row['sha256'])
        pair = row.get('packs')
        require(isinstance(pair, list) and len(pair) == 2, 'author requires one complete pair')
        for pack in pair:
            require(isinstance(pack, dict) and set(pack) == {'uuid', 'version'}
                    and isinstance(pack['uuid'], str) and bool(pack['uuid']) and pack['uuid'] not in uuids,
                    'duplicate or invalid author UUID')
            require(isinstance(pack['version'], list) and len(pack['version']) == 3
                    and all(type(n) is int and n >= 0 for n in pack['version']), 'invalid author version')
            uuids.add(pack['uuid'])
    require(names == set(authors) | set(deferred), 'full catalog must equal active plus explicitly deferred authors')
    active, postponed = [], []
    for row in upstream:
        name = row['name']
        if name in deferred:
            review = deferred[name]
            require(isinstance(review, dict) and set(review) == {'upstream', 'reason'}
                    and review['upstream'] == row and isinstance(review['reason'], str) and bool(review['reason'].strip()),
                    'deferred author differs from its exact reviewed row or reason')
            postponed.append(copy.deepcopy(review))
            continue
        pin = authors[name]
        require(set(row) == {'name', 'project_id', 'file_id', 'sha256', 'packs'}
                and all(row[key] == pin[key] for key in ('project_id', 'file_id', 'sha256')), 'selected author identity differs: ' + name)
        pair = {pin['behavior_uuid']: pin['author_version'], pin['resource_uuid']: pin['author_version']}
        require(len(pair) == 2 and {pack['uuid']: pack['version'] for pack in row['packs']} == pair,
                'selected author pair differs: ' + name)
        outputs = [{'uuid': pin[uuid], 'side': label, 'version': selection['pack_versions'][name][side]}
                   for side, label, uuid in [('BP', 'behavior', 'behavior_uuid'), ('RP', 'resource', 'resource_uuid')]]
        active.append({'upstream': copy.deepcopy(row), 'outputs': copy.deepcopy(outputs)})
    return {
        'schema': 1, 'kind': 'current-author-curated-upstream',
        'full_lock_sha256': hashlib.sha256(json.dumps(lock, sort_keys=True).encode()).hexdigest(),
        'policy_sha256': declaration_sha({'authors': catalog['authors'], 'policy': policy}),
        'profile': {'path': catalog['selection']['path'], 'sha256': catalog['selection']['sha256'], 'name': catalog['profile']},
        'owner': {'repository': baseline['repository'], 'commit': commit, 'version': list(baseline['version']),
                  'packs': {label: baseline['packs'][side]['uuid'] for side, label in [('BP', 'behavior'), ('RP', 'resource')]}},
        'active': active, 'deferred': postponed,
    }


def validate_curated_upstream_receipt(receipt, expected):
    """Require the exact active pairs and reject deferred packs under any owner."""
    def require(condition, message):
        if not condition:
            raise ValueError('Curated upstream receipt: ' + message)

    require(receipt.get('upstream_selection') == expected, 'selection proof differs from current committed sources')
    packs = receipt['packs']
    rows = {row['uuid']: row for row in packs}
    require(len(rows) == len(packs), 'duplicate pack UUID')
    active = {pack['uuid']: (item['upstream'], pack) for item in expected['active'] for pack in item['outputs']}
    postponed = {pack['uuid'] for item in expected['deferred'] for pack in item['upstream']['packs']}
    require(not postponed & set(rows), 'deferred author pack re-entered the candidate')
    require({row['uuid'] for row in packs if row['source'].get('owner') in ('upstream', 'upstream_extended')} == set(active),
            'active upstream pair inventory differs')
    catalog = [item['upstream'] for item in expected['active'] + expected['deferred']]
    identities = {field: {row[field] for row in catalog} for field in ('project_id', 'file_id', 'sha256')}
    for uid, row in rows.items():
        source = row['source']
        if uid in active:
            upstream, pack = active[uid]
            require(row['side'] == pack['side'] and row['version'] == pack['version'], 'selected output pair differs')
            require(source.get('owner') in ('upstream', 'upstream_extended')
                    and source.get('archive_sha256') == upstream['sha256']
                    and all(source.get(key) == upstream[key] for key in ('project_id', 'file_id')), 'selected source identity differs')
        else:
            require(source.get('archive_sha256') not in identities['sha256']
                    and all(source.get(key) not in identities[key] for key in ('project_id', 'file_id')),
                    'catalog author disguised as another pack owner')
    owner = expected['owner']
    require({row['uuid'] for row in packs if row['source'].get('repository') == owner['repository']} == set(owner['packs'].values()),
            'private selection owner pair differs')
    for side, uid in owner['packs'].items():
        row = rows[uid]
        require(row['side'] == side and row['version'] == owner['version'] and row['source'].get('owner') == 'owned'
                and row['source'].get('commit') == owner['commit'], 'private selection owner binding differs')
    require(set(receipt['order']) == {'behavior', 'resource'}, 'candidate order sides differ')
    for side, order in receipt['order'].items():
        require(len(order) == len(set(order)) and set(order) == {row['uuid'] for row in packs if row['side'] == side},
                'candidate order does not cover its complete pack set')


def receipt(profile):
    result = {key: profile[key] for key in ['id', 'version', 'original_files', 'patched_files', 'copies']}
    if profile.get('removed_files'):
        result['removed_files'] = profile['removed_files']
    return result


def public_profiles():
    return {'public-api': CATALOG['public_api_profile'], **CATALOG.get('public_api_profiles', {})}


def public_predecessors(profile):
    # The original receipt remains the default. Only the named, unchanged
    # private declarations may use another reviewed public API predecessor.
    for name, accepted in CATALOG.get('public_api_predecessors', {}).items():
        if PROFILES.get(name) == profile:
            profiles = public_profiles()
            return [receipt(profiles[key]) for key in accepted]
    return [CATALOG['public_api']]


def validate_stable_source(profile, source):
    if source.get('owner') != profile['source_owner'] or source.get('archive_sha256') != profile['archive_sha256']:
        raise ValueError('stable host requires its exact preceding author source')
    prior = source.get('reviewed_extensions', [])
    if not isinstance(prior, list):
        raise ValueError('stable host preceding receipts must be a list')
    for name in profile['required_extensions']:
        expected = public_predecessors(profile) if name == 'public-api' else [receipt(PROFILES[name])]
        preceding = prior
        if name == 'public-api':
            public_ids = {p['id'] for p in public_profiles().values()} | {p['id'] for p in expected}
            preceding = [row for row in prior if isinstance(row, dict) and row.get('id') in public_ids]
            # A host has one public API source, not two sequential installations
            # or a mixture of a new identity and old helper hashes.
            if len(preceding) != 1:
                raise ValueError('stable host lacks exact preceding receipt: ' + name)
        def matches(row, option):
            if not isinstance(row, dict):
                return False
            if all(row.get(key) == value for key, value in option.items()):
                return True
            if name == 'public-api' and row.get('delegated_files'):
                from cookery_station_extension import validate_public_delegation
                try:
                    validate_public_delegation(row, option)
                    return True
                except (ValueError, KeyError, TypeError):
                    return False
            return False
        if not any(matches(row, option) for row in preceding for option in expected):
            raise ValueError('stable host lacks exact preceding receipt: ' + name)


def match_stable_profile(spec, owned_root=None, source=None):
    candidates = {**PROFILES, **public_profiles()}
    new_hosts = {p['host_uuid'] for p in candidates.values()}
    new_archives = {p.get('archive_sha256') for p in candidates.values()} - {None}
    if spec.get('host_uuid') not in new_hosts and spec.get('archive_sha256') not in new_archives:
        return None
    found = [(name, p) for name, p in candidates.items()
             if p['id'] == spec.get('id') and p['host_uuid'] == spec.get('host_uuid')]
    if not found:
        raise ValueError('unregistered stable host declaration')
    # Distinct owner releases may share the author UUID and extension ID.
    # Match the full reviewed declaration; never choose the newest by name.
    exact = [(name, profile) for name, profile in found if declaration_sha(spec) == profile['spec_sha256']]
    if len(exact) != 1:
        raise ValueError('stable host declaration differs from the exact reviewed profile: ' + spec['id'])
    name, profile = exact[0]
    if source is not None:
        validate_stable_source(profile, source)
    if owned_root is not None:
        for record in profile['copies'].values():
            path = owned_root / record['source']
            if path.is_symlink() or not path.resolve().is_relative_to(owned_root.resolve()) or not path.is_file():
                raise ValueError('stable host helper missing or outside owned source')
            if hashlib.sha256(path.read_bytes()).hexdigest() != record['sha256']:
                raise ValueError('stable host helper differs from the exact reviewed source')
    return profile


def current_author_profile(spec, owned_root=None, source=None):
    """A fresh owner uses one exact declaration, never an owner-version range."""
    profile = match_stable_profile(spec, owned_root, source)
    return profile if profile and profile.get('admission') in ('current-author-p55', 'current-author-p56', 'current-author-p57','current-author-p58', CURATED) else None
