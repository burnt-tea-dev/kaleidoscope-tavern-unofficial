/** Build the legacy API's small product view from the canonical full guide. */
import {readFileSync,writeFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
import {fileURLToPath} from 'node:url';
import {buildCookeryGuidePayload} from '../runtime/BP/scripts/data/cookery-guide-payload.js';
import {BUILTIN_RECIPES} from '../runtime/BP/scripts/data/recipes.js';
import {SHAKER_RECIPES} from '../runtime/BP/scripts/data/mixology.js';

const root=new URL('../',import.meta.url);
const output=new URL('runtime/BP/scripts/data/legacy-guide-products.js',root);
const recipes=[...BUILTIN_RECIPES,...SHAKER_RECIPES];
const payload=buildCookeryGuidePayload({list:()=>[],allPages:()=>[],allRecipes:()=>recipes});
const products=[];
// Read the two actual declarative consumers without importing the runtime
// projection. This lets the generator repair a stale/missing product table.
for(const name of ['guide-pages.js','mixology-pages.js']){
 const source=readFileSync(new URL('runtime/BP/scripts/data/'+name,root),'utf8');
 const pattern=/import\s*\{\s*legacyGuidePage\s*\}\s*from\s*['"]\.\/legacy-guide-projection\.js['"];?/g;
 if([...source.matchAll(pattern)].length!==1)throw Error('Unexpected legacy page imports: '+name);
 const body=source.replace(pattern,'').replace(/export\s+const\s+/g,'const ');
 if(/\b(?:import|export)\s/.test(body))throw Error('Unexpected legacy page dependencies: '+name);
 runInNewContext(body,{legacyGuidePage(id,title,rows){
  if(typeof id!=='string'||!title||!Array.isArray(rows)||rows.some(x=>typeof x!=='string'))throw Error('Invalid legacy page: '+name);
  products.push(...rows);return undefined;
 }},{filename:name,timeout:1000});
}
const table={};
for(const short of new Set(products)){
 const entry=payload.entries.find(row=>row.id==='kaleidoscope_tavern:'+short);
 if(!entry)throw Error('Missing canonical guide product: '+short);
 table[short]={id:entry.id,mechanicsByLocale:Object.fromEntries(['zh_CN','zh_TW','en_US'].map(lc=>[lc,entry.mechanicsByLocale?.[lc]??entry.mechanics??[]]))};
}
const recipeProducts=recipes.map(row=>({id:row.id,product:row.output?.item??row.output?.byQuality?.[0]}))
 .filter(row=>Object.values(table).some(entry=>entry.id===row.product));
const generated='// Generated by tools/build_legacy_guide_projection.mjs; keep canonical guide data authoritative.\n'
 +'export const LEGACY_GUIDE_PRODUCTS='+JSON.stringify(table,null,2)+';\n'
 +'export const LEGACY_GUIDE_RECIPE_PRODUCTS='+JSON.stringify(recipeProducts,null,2)+';\n';
if(process.argv.includes('--check')){
 if(readFileSync(output,'utf8')!==generated)throw Error('Stale legacy guide projection; run node tools/build_legacy_guide_projection.mjs');
 console.log('Canonical legacy guide projection current: '+Object.keys(table).length+' products.');
}else{
 writeFileSync(output,generated);
 console.log('Generated '+fileURLToPath(output)+' ('+Object.keys(table).length+' products).');
}
